import Foundation
import os.log

private let log = Logger(subsystem: "com.nomily.app.ios", category: "jobs")

/// The kind of job.
///
/// ★ Added in the twelfth revision, 2026-10-16. Four kinds, but **this queue only handles three of them** — see the
/// "why transcription isn't in here" note at the top of `JobQueue`.
enum JobKind: String, Codable, CaseIterable {
    /// Batch transcription (ASR). **Exists only as an enum member**, so the task overview page can put
    /// all four kinds in one list; its scheduling still lives in `TranscriptionService`.
    case transcribe
    case summarize
    case translate
    case export
    /// ★ 2026-10-23 ("录音来源里面还有大纲总结"): the timestamped chapter
    /// outline shown at the top of 来源. A separate kind (not part of
    /// `summarize`) because it is generated **per transcript**, can be re-run
    /// on its own, and must not fight over the note page a summary writes.
    case outline

    var symbol: String {
        switch self {
        case .transcribe: return "waveform"
        case .summarize:  return "sparkles"
        case .translate:  return "character.book.closed"
        case .export:     return "square.and.arrow.up"
        case .outline:    return "list.bullet.rectangle"
        }
    }

    var title: String {
        switch self {
        case .transcribe: return L10n.Jobs.kindTranscribe
        case .summarize:  return L10n.Jobs.kindSummarize
        case .translate:  return L10n.Jobs.kindTranslate
        case .export:     return L10n.Jobs.kindExport
        case .outline:    return L10n.Jobs.kindOutline
        }
    }
}

/// A job that **isn't finished yet** (or has just finished).
///
/// ## Why the parameters are a "flat bag of optionals" instead of an enum with associated values
/// Each kind's parameters are only one or two items, and all of them are "strings/numbers" that go straight into JSON.
/// Writing a `Codable` conformance for each (plus associated-value encoding for `JobKind`, and a decoding branch per kind)
/// would balloon this file threefold, bought only for "tighter typing" — and the only consumer of those parameters
/// is `JobRunners` in this same file, where one `switch` lays them all out in plain sight.
///
/// ⚠️ The bag is **forward-compatible**: the synthesized `init(from:)` uses `decodeIfPresent` for `Optional` fields, so
///    **a jobs-queue.json from an older build, missing new fields, still decodes**,
///    and adding a fourth kind later won't touch decoding. That's this design's only advantage over an associated-value enum — don't lose it.
///
/// ⚠️ `id` is an **idempotency key**: enqueueing the same `id` again doesn't create a second job; it resets
///    the retry counter (the user actively tapped again, so the previous give-up doesn't count). Same idea as
///    `TranscriptionService.PendingJob` keying by file name.
struct Job: Codable, Identifiable, Equatable {
    var id: String
    var kind: JobKind
    /// Which recording this job is attached to (`LibraryItem.name`). Also the UI's main title.
    var clipName: String
    var attempts: Int = 0
    /// Why the last attempt failed. **Stays nil on success** — the UI can tell "finished" from "gave up after max attempts" with just
    /// this field plus `finishedAt`; no third status field needed.
    var lastError: String?
    var enqueuedAt: Date
    /// When the run finished (success or give-up). `nil` = not yet dequeued.
    var finishedAt: Date?

    /// Chunk progress. Only the summary path fills this (`LLMCompletionService.completeChunked`).
    var progressDone: Int?
    var progressTotal: Int?
    /// The **result note** the runner appends after the run ("actually generated by the Ollama fallback",
    /// "the content was too long and split into 5 chunks").
    ///
    /// ⚠️ Why it must be persisted along with the output instead of living only in view memory: after the twelfth revision,
    ///    a job **will often finish while the user isn't looking** (that's the entire point of the change),
    ///    and by the time the user comes back the `Outcome` is long gone. If the note can't survive, the user's question —
    ///    "I set Open Router, so why was this generated by Ollama?" — goes unanswered forever.
    var notes: [String]?
    /// The model itself said it hit the output cap and the body is **truncated**. A half-cut summary reads exactly like
    /// a complete one, so this flag must reach the UI — it can't be silently swallowed.
    var wasTruncated: Bool?

    // MARK: Parameters (read per kind; nil for the rest)

    /// `summarize`: the **final** system prompt (output-language instruction already appended).
    ///
    /// ⚠️ What's stored is the finished prompt, not the template id: this job may not be picked up until **days later** by a
    ///    "restart and resume" days later, by which time the user may well have edited or deleted that template.
    ///    A job's content should be frozen at "the moment the user pressed the button", not drift with the configuration.
    var prompt: String?
    /// `summarize`: the template name. **For display only**; the run never reads it.
    var templateName: String?
    /// `summarize`: which **note page** this job writes (`NotePage.id`).
    ///
    /// ★ 2026-10-23 ("页面模板"). `nil` means the primary summary page — nil keeps
    /// every pre-existing ledger entry and call site meaning exactly what they
    /// always did (see the forward-compatibility note on the struct).
    var pageID: String?
    /// `translate`: the target language's English name (fed into the prompt; see `LLMCompletionService.translate`).
    var languageName: String?
    /// `translate`: whether it's the transcript or the summary being translated (`"transcript"` / `"summary"`).
    var translateTarget: String?
    /// `export`：`m4a` / `wav`。
    var exportFormat: String?

    /// Not a single attempt has finished, so it can still be retried — the same test as the
    /// `attempts < maxAttempts` check in `TranscriptionService.runDrainLoop`.
    var isRunnable: Bool { finishedAt == nil && attempts < JobQueue.maxAttempts }

    /// The bit the UI subtitle needs: "which kind of job, which variant".
    var detail: String? {
        switch kind {
        case .summarize: return templateName
        case .translate:
            if let name = languageName, let target = translateTarget {
                return target == "summary"
                    ? L10n.Jobs.detailTranslatedSummary(name)
                    : L10n.Jobs.detailTranslatedTranscript(name)
            }
            return languageName
        case .export:    return exportFormat?.uppercased()
        case .transcribe: return nil
        case .outline:   return nil
        }
    }
}

/// A job that can **never succeed** (the source file is gone).
///
/// A separate type so the queue can tell it apart from "this attempt failed, retry later":
/// on the `TranscriptionService` side, `fileExists` in the drain loop leads straight to `forget`;
/// here the three kinds have different "sources" (export needs the audio, summary and translation need the transcript or summary file),
/// and only the runner knows what's missing — so it throws the verdict and the queue acts on it.
struct JobSourceMissing: LocalizedError {
    let what: String
    var errorDescription: String? { L10n.Jobs.sourceMissing(what) }
}

/// The **persisted ledger + serial pump** for the three long-running kinds: summary / translation / format conversion.
///
/// ## Why it exists
/// The user's words: **"generate summary, translation, transcription, and audio format conversion... you can exit to the
/// background first and check and analyze when it's done"**.
///
/// Taken apart, the "keep running after switching away" half **already held**: of `BackgroundKeeper`'s four tokens,
/// `summary` / `export` were already in use, and silent audio + the `audio` background mode withstands
/// switching away, a locked screen, even long stretches left running. What was actually missing was the other half: **when the system kills the process (or the user
/// force-quits it), these three kinds vanish into thin air** — transcription has a persisted list (
/// `transcription-queue.json`) it can recover from; the other three kinds had only in-memory `Task`s.
/// The user taps "Generate summary" on the detail page, switches away, comes back to find nothing happened — that gap was exactly this.
///
/// So this class looks **almost identical** to the `TranscriptionService` queue (attempt counting,
/// exponential backoff, retryability test, serial pump, cross-launch recovery) — because that's exactly the semantics needed here.
///
/// ## ★ Why transcription was **not** moved in (a deliberate "inconsistency")
/// Merging all four kinds into one `Job<Kind>` is the prettier abstraction, but the cost is rewriting
/// the most critical stretch of `TranscriptionService`'s 620 lines: it carries a whole set of battle-tested semantics —
/// dedupe by file name (the same recording requested by two UI paths runs once), `enqueueAndWait`
/// (the watch-delivery path waits for the dequeue before refreshing the library), orphan cleanup at launch, and an
/// **ASR-specific** retryability test (missing key / unconfigured provider / too-short audio never retry; everything else does).
/// None of those semantics can be assumed by **looks-like-equivalence** — not even one — and in this app transcription is the one path
/// users have used repeatedly and have explicitly called "always failing".
///
/// ⇒ Conclusion: **what's shared is the "task overview" layer, not the "scheduling" layer.** The overview page
///   (`TaskCenterView`) puts `transcription.pending` and this file's `jobs` into the same
///   list; each side keeps its own pump, its own persistence, and its own retryability test.
///   If the two kinds ever genuinely need to yield to each other (say, "summary waits for transcription to finish"), then talk about merging —
///   the reason to merge then would be **coupling**, not "it looks like it should be unified".
///
/// ## Why the pump is serial
/// Two of the three kinds hit the same LLM (`LLMCompletionService`), and local Ollama's inference
/// is inherently serial — concurrent submissions would only slow both sides down and blow
/// past the 3B model's `num_ctx`. Export (CPU/IO) queued behind it merely starts a bit later; it won't fail. Same verdict as
/// "the ASR side already had headroom" in `TranscriptionService.runDrainLoop`.
@MainActor
final class JobQueue: ObservableObject {

    /// How many rounds a job gets: 1 first run + 2 retries. Same figure as the transcription side —
    /// a local Ollama round takes minutes, and five attempts would make users think it's hung.
    ///
    /// ⚠️ `nonisolated`: `Job.isRunnable` is a nonisolated computed property on a value type, and this needs to read it.
    ///    Without it the code compiles but errors with "main actor-isolated static property can not be
    ///    referenced from a nonisolated autoclosure" — a **hard error** in Swift 6.
    ///    An immutable `let` + `Int` gains nothing from isolation; dropping it is safe.
    nonisolated static let maxAttempts = 3

    /// How long finished jobs stick around. The overview page must be able to answer "did that job I started finish?", so completed entries
    /// are **not deleted immediately**; but they can't pile up forever — a day covers "come back tomorrow and look".
    nonisolated static let finishedRetention: TimeInterval = 24 * 3600
    /// The maximum number of finished jobs kept (oldest dropped beyond it). Both gates work together: time handles the everyday,
    /// count handles the extreme of "hundreds of title jobs run in one day".
    nonisolated static let finishedLimit = 60

    /// Queued + just-finished jobs, newest enqueue first.
    @Published private(set) var jobs: [Job] = []

    /// The job (`id`) currently executing. The UI uses it to tell "in progress" from "queued".
    @Published private(set) var running: Set<String> = []

    /// The runner for each kind. **Registered by the composition root** (`AppEnvironment`); this file doesn't
    /// reference the LLM / exporter directly — otherwise this class would have to know how three services are constructed,
    /// when all it really needs is "give me a job, I'll run it and report back".
    typealias Runner = @MainActor (Job, Reporter) async throws -> Void

    /// The small handle runners use to talk back: report progress while running, append a note when done.
    ///
    /// ⚠️ A struct rather than two closure parameters: adding another kind of report later (say, "I'm actually
    ///    blocked by another job") won't require changing `Runner`'s three signatures and three runners at once.
    ///
    /// ⚠️ Function-type parameters **can't have argument labels** (`(done: Int, total: Int) -> Void` is
    ///    a compile error), so bare `Int`s are used throughout; call sites self-document via field names.
    struct Reporter {
        /// Chunk progress (long transcription). **Not required to be reported** — without it you just get "spinner without numbers",
        /// the same behavior as before the twelfth revision.
        let progress: (Int, Int) -> Void
        /// Appends the "result note for the user" after finishing. See `Job.notes`.
        /// Parameters are `(note, whether the result was truncated)`.
        let notes: ([String], Bool) -> Void
    }

    private var runners: [JobKind: Runner] = [:]
    private var drainTask: Task<Void, Never>?
    /// A continuation waiting for a given `id` to dequeue (`wait(for:)`).
    private var waiters: [String: [CheckedContinuation<Job?, Never>]] = [:]

    init() {
        jobs = Self.load()
        pruneFinished()
    }

    // MARK: - Registering runners

    /// Idempotent: registering the same kind again just overwrites (the composition root only calls once, but overwrite beats crash).
    func register(_ kind: JobKind, runner: @escaping Runner) {
        runners[kind] = runner
    }

    // MARK: - Enqueue / queries

    /// Enqueue. **Persist first, run second** — the difference only shows in the one case of "app killed midway".
    func enqueue(_ job: Job) {
        guard job.kind != .transcribe else {
            // Transcription has its own queue via `TranscriptionService`; this guard exists so the caller's
            // error blows up on the spot instead of quietly lining up in a queue that will never run.
            assertionFailure("transcribe jobs belong to TranscriptionService, not JobQueue")
            return
        }
        if let idx = jobs.firstIndex(where: { $0.id == job.id }) {
            // Already in the queue: don't add a duplicate, but reset the retry counter and turn the just-finished entry back into pending
            // (the user actively asked again, meaning they weren't satisfied with the last result).
            jobs[idx].attempts = 0
            jobs[idx].lastError = nil
            jobs[idx].finishedAt = nil
            jobs[idx].progressDone = nil
            jobs[idx].progressTotal = nil
            jobs[idx].notes = nil
            jobs[idx].wasTruncated = nil
            jobs[idx].enqueuedAt = Date()
            // The **new** parameters win: the user may have switched templates / target language /
            // export format — that makes it a different job.
            jobs[idx] = merged(jobs[idx], with: job)
        } else {
            jobs.insert(job, at: 0)
        }
        save()
        log.info("enqueued \(job.kind.rawValue, privacy: .public) id=\(job.id, privacy: .public)")
        startDrainIfNeeded()
    }

    /// Keep the old entry's identity and counters, overwrite with the new entry's parameters.
    private func merged(_ old: Job, with new: Job) -> Job {
        var merged = new
        merged.id = old.id
        merged.kind = old.kind
        merged.clipName = old.clipName
        merged.enqueuedAt = old.enqueuedAt
        return merged
    }

    func job(id: String) -> Job? { jobs.first { $0.id == id } }

    /// Unfinished jobs on this recording (the UI uses it to decide whether the button reads "Start" or "In progress").
    func activeJobs(for clipName: String) -> [Job] {
        jobs.filter { $0.clipName == clipName && $0.finishedAt == nil }
    }

    func isRunning(id: String) -> Bool { running.contains(id) }

    /// The three states the UI uses.
    enum State: Equatable {
        case waiting, running, done, gaveUp
    }

    func state(of job: Job) -> State {
        if running.contains(job.id) { return .running }
        if job.finishedAt != nil { return job.lastError == nil ? .done : .gaveUp }
        return .waiting
    }

    /// Count of unfinished entries (queued and in progress). The Settings row uses it to decide whether to appear.
    var unfinishedCount: Int {
        jobs.filter { $0.finishedAt == nil }.count
    }

    /// Count of finished entries (success + give-up). The overview page uses it to decide whether to show "Clear finished".
    var finishedCount: Int {
        jobs.filter { $0.finishedAt != nil }.count
    }

    // MARK: - Cancel / retry / cleanup

    /// Cancel a job.
    ///
    /// The one already running is interrupted via `Task.cancel()` (the URLSession requests inside the runner
    /// break with it); one still queued is handled by **marking it "finished with no error"** — i.e. dequeued,
    /// but not counted among the "gave up" entries. Cancellation is the user's intent, not a failure.
    func cancel(id: String) {
        guard let idx = jobs.firstIndex(where: { $0.id == id }) else { return }
        runningTasks[id]?.cancel()
        runningTasks[id] = nil
        guard jobs[idx].finishedAt == nil else { return }
        jobs[idx].finishedAt = Date()
        jobs[idx].lastError = nil
        jobs[idx].progressDone = nil
        jobs[idx].progressTotal = nil
        // A cancelled job shouldn't keep the previous attempt's result note — that wasn't this run's result.
        jobs[idx].notes = nil
        jobs[idx].wasTruncated = nil
        save()
        log.info("cancelled \(id, privacy: .public)")
        resumeWaiters(id: id)
    }

    /// Try again. **Regains the full 3 attempts**, same rule as "the user actively asked again, so the previous
    /// give-up doesn't count" in `TranscriptionService.enqueue`.
    func retry(id: String) {
        guard let idx = jobs.firstIndex(where: { $0.id == id }) else { return }
        jobs[idx].attempts = 0
        jobs[idx].lastError = nil
        jobs[idx].finishedAt = nil
        jobs[idx].notes = nil
        jobs[idx].wasTruncated = nil
        jobs[idx].enqueuedAt = Date()
        save()
        startDrainIfNeeded()
    }

    /// Wipe an entry from the ledger entirely (the user has seen it and doesn't want it / the source is gone).
    func forget(id: String) {
        guard jobs.contains(where: { $0.id == id }) else { return }
        jobs.removeAll { $0.id == id }
        save()
    }

    func clearFinished() {
        jobs.removeAll { $0.finishedAt != nil }
        save()
    }

    /// All jobs for one recording (torn down together when the recording is deleted / cleared).
    func forgetAll(clipName: String) {
        let before = jobs.count
        jobs.removeAll { $0.clipName == clipName }
        guard jobs.count != before else { return }
        save()
    }

    // MARK: - Start / stop

    /// Restart the unfinished jobs. Hooked at two points: `AppEnvironment.init` (cold launch)
    /// and `RootView` returning to the foreground — perfectly symmetric with `transcription.resumePending()`.
    ///
    /// Re-entry is guarded by `startDrainIfNeeded`; repeat calls are safe.
    func resume() {
        guard jobs.contains(where: { $0.isRunnable }) else { return }
        startDrainIfNeeded()
    }

    /// Wait for a job to **dequeue** (success, gave up after max attempts, cancelled, or source gone).
    ///
    /// For callers that must refresh the UI only after the result (same purpose as
    /// `TranscriptionService.enqueueAndWait`).
    /// Returns immediately if the entry is no longer in the queue — that means it finished **before it was
    /// even enqueued**, and waiting would only hang the caller.
    @discardableResult
    func wait(for id: String) async -> Job? {
        guard let snapshot = job(id: id), snapshot.finishedAt == nil else {
            return job(id: id)
        }
        return await withCheckedContinuation { cont in
            waiters[id, default: []].append(cont)
        }
    }

    // MARK: - Pump

    private func startDrainIfNeeded() {
        guard drainTask == nil else { return }
        drainTask = Task { @MainActor [weak self] in
            guard let self else { return }
            await self.runDrainLoop()
            self.drainTask = nil
        }
    }

    /// Running job → its `Task` (for cancellation).
    ///
    /// ⚠️ The extra `Task` layer instead of awaiting `runner(...)` directly has exactly one purpose: getting
    ///   a handle that can be `cancel()`ed. `cancel(id:)` is also `@MainActor`, so there's no race between
    ///   "storing into the dictionary" and "being cancelled" — the store happens before the first `await`.
    private var runningTasks: [String: Task<Result<Void, Error>, Never>] = [:]

    /// Run the queue's jobs one at a time.
    private func runDrainLoop() async {
        while let job = jobs.first(where: { $0.isRunnable }) {
            guard let runner = runners[job.kind] else {
                // The composition root didn't register this kind (impossible, but silently not running would leave the queue
                // stuck on the same entry forever — the hardest kind of "nothing happened" to debug).
                log.error("no runner registered for \(job.kind.rawValue, privacy: .public); dropping")
                markFinished(id: job.id, error: L10n.Jobs.noRunner)
                continue
            }
            running.insert(job.id)

            // ⚠️ Must use `Task { }` (with `_inheritActorContext`), not
            //    `.task` / `Task.detached`: the latter two's closures are `@Sendable`, and capturing
            //    this closure-holding class trips concurrency checks, and this project builds with zero warnings
            //    (same pitfall: see the note at the top of `WatchBotFace`).
            let handle = Task { @MainActor in
                let reporter = Reporter(
                    // Both callbacks are [weak self]: once a job is running, the queue **shouldn't** be kept alive by
                    // these closures (it does live to process end anyway, but that's coincidence, not contract).
                    progress: { [weak self] done, total in
                        self?.recordProgress(id: job.id, done: done, total: total)
                    },
                    notes: { [weak self] notes, truncated in
                        self?.recordNotes(id: job.id, notes: notes, truncated: truncated)
                    }
                )
                do {
                    try await runner(job, reporter)
                    return Result<Void, Error>.success(())
                } catch {
                    return Result<Void, Error>.failure(error)
                }
            }
            runningTasks[job.id] = handle
            let outcome = await handle.value

            runningTasks[job.id] = nil
            running.remove(job.id)

            switch outcome {
            case .success:
                markFinished(id: job.id, error: nil)
            case .failure(let error) where error is JobSourceMissing:
                // Source is gone (recording deleted, transcript cleared). Ten thousand retries won't help;
                // wipe it outright — same verdict as the `forget(name:)` step in the transcription queue.
                log.info("dropping \(job.id, privacy: .public) — \(error.localizedDescription, privacy: .public)")
                forget(id: job.id)
                resumeWaiters(id: job.id)
            case .failure(let error) where Self.isCancellation(error):
                // The user cancelled: treat as "finished with no error", keep it in the list but don't retry.
                markFinished(id: job.id, error: nil)
            case .failure(let error):
                guard let idx = jobs.firstIndex(where: { $0.id == job.id }) else { continue }
                jobs[idx].attempts += 1
                jobs[idx].lastError = error.localizedDescription
                let attempts = jobs[idx].attempts
                save()
                if attempts >= Self.maxAttempts {
                    log.warning("giving up on \(job.id, privacy: .public) after \(attempts) attempts")
                    markFinished(id: job.id, error: error.localizedDescription)
                    continue
                }
                try? await Task.sleep(for: Self.backoff(afterAttempt: attempts))
            }
        }
    }

    /// Finished (success / give-up / cancel). **Doesn't delete the entry** — see `finishedRetention`.
    private func markFinished(id: String, error: String?) {
        guard let idx = jobs.firstIndex(where: { $0.id == id }) else { return }
        jobs[idx].finishedAt = Date()
        jobs[idx].lastError = error
        jobs[idx].progressDone = nil
        jobs[idx].progressTotal = nil
        save()
        resumeWaiters(id: id)
    }

    private func recordProgress(id: String, done: Int, total: Int) {
        guard let idx = jobs.firstIndex(where: { $0.id == id }) else { return }
        jobs[idx].progressDone = done
        jobs[idx].progressTotal = total
        // ⚠️ **Not persisted**: chunk progress is a high-frequency write, once per chunk (a long transcription has dozens),
        // and its value exists only during the few minutes "the user is watching this page". Losing progress when the process is killed
        // and re-reporting from the start next round costs far less than an atomic write per chunk.
    }

    /// Appends the result note after the run (see `Job.notes`).
    ///
    /// ⚠️ **Not persisted here either**: the `markFinished` right after always calls `save()`, and the two
    ///    writes hit the same file. Between this callback and the `return` inside the runner there's no `await`
    ///    (if there were, the call site would insert `try Task.checkCancellation()`), so there's no
    ///    window of "note written but markFinished never reached".
    private func recordNotes(id: String, notes: [String], truncated: Bool) {
        guard let idx = jobs.firstIndex(where: { $0.id == id }) else { return }
        jobs[idx].notes = notes.isEmpty ? nil : notes
        jobs[idx].wasTruncated = truncated ? true : nil
    }

    private func resumeWaiters(id: String) {
        guard let list = waiters.removeValue(forKey: id) else { return }
        let snapshot = job(id: id)
        for cont in list { cont.resume(returning: snapshot) }
    }

    /// The wait after attempt `attempt` fails. Same numbers as the transcription side — exponential backoff (2/8/30 seconds),
    /// capped nowhere near minutes: the user is most likely watching this progress, and erroring early so they can tap again beats a long wait.
    private static func backoff(afterAttempt attempt: Int) -> Duration {
        switch attempt {
        case 1: return .seconds(2)
        case 2: return .seconds(8)
        default: return .seconds(30)
        }
    }

    /// The two shapes of cancellation: Swift Concurrency's `CancellationError`, and `URLError.cancelled`
    /// thrown when a URLSession request is cancelled. **Both must be recognized**.
    private static func isCancellation(_ error: Error) -> Bool {
        if error is CancellationError { return true }
        if let urlError = error as? URLError, urlError.code == .cancelled { return true }
        return false
    }

    // MARK: - Disk

    private static func load() -> [Job] {
        guard let data = try? Data(contentsOf: StorageLocations.jobsQueueURL),
              let decoded = try? JSONDecoder().decode([Job].self, from: data) else {
            return []
        }
        return decoded
    }

    private func save() {
        let encoder = JSONEncoder()
        encoder.outputFormatting = [.prettyPrinted, .sortedKeys]
        guard let data = try? encoder.encode(jobs) else { return }
        try? FileManager.default.createDirectory(
            at: StorageLocations.root, withIntermediateDirectories: true
        )
        try? data.write(to: StorageLocations.jobsQueueURL, options: .atomic)
    }

    /// Clean up old finished entries at launch. **Only "finished" ones** — not a single unfinished entry may be touched
    /// (that's the entire reason this file exists).
    ///
    /// Two gates: time (`finishedRetention`) handles the everyday, count (`finishedLimit`) handles
    /// the "hundreds run in one day" extreme. `jobs` is **newest first**, so within a single pass,
    /// "the finished entries past the first `limit` counted from the front" are exactly the oldest ones.
    private func pruneFinished() {
        let cutoff = Date().addingTimeInterval(-Self.finishedRetention)
        var kept: [Job] = []
        var finishedKept = 0
        for job in jobs {
            if let finishedAt = job.finishedAt {
                guard finishedAt >= cutoff else { continue }
                finishedKept += 1
                guard finishedKept <= Self.finishedLimit else { continue }
            }
            kept.append(job)
        }
        guard kept.count != jobs.count else { return }
        jobs = kept
        log.info("pruned \(self.jobs.count - kept.count) finished job(s) on load")
        save()
    }
}
